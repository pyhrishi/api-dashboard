/**
 * Partner & Affiliate Revenue-Sharing Engine
 * Tracks partner referrals, calculates tiered commissions, and manages payouts.
 * Supports: Resellers, Referral Affiliates, White-Label OEM Partners, Technology Partners.
 */

// ─── Types ────────────────────────────────────────────────────────────────────

export type PartnerTier = 'affiliate' | 'silver' | 'gold' | 'platinum' | 'oem';
export type CommissionType = 'percentage' | 'flat_per_call' | 'revenue_share';
export type PayoutStatus = 'pending' | 'approved' | 'paid' | 'held';
export type RevenueEventType = 'api_call' | 'subscription_upgrade' | 'contract_signed' | 'renewal';

export interface PartnerRecord {
  partnerId: string;
  name: string;
  tier: PartnerTier;
  referralCode: string;
  commissionConfig: CommissionConfig;
  cumulativeRevenue: number;   // Total revenue generated by this partner's referrals
  cumulativeEarnings: number;  // Total commission earned (lifetime)
  pendingPayout: number;       // Unpaid balance
  joinedAt: number;
}

export interface CommissionConfig {
  type: CommissionType;
  /** For 'percentage' and 'revenue_share': e.g. 0.2 = 20% */
  rate: number;
  /** For 'flat_per_call': USD per credit consumed */
  flatRatePerCredit?: number;
  /** Hard cap per calendar month in USD */
  monthlyCap?: number;
  /** Bonus threshold: extra % if partner drives > $X/month */
  acceleratorThreshold?: number;
  acceleratorBonus?: number;
}

export interface RevenueEvent {
  eventId: string;
  partnerId: string;
  referredApiKey: string;  // The end-customer's key that was referred by this partner
  eventType: RevenueEventType;
  grossRevenue: number;    // USD gross revenue from end-customer
  creditsConsumed?: number;
  commissionEarned: number;
  timestamp: number;
}

export interface PayoutRecord {
  payoutId: string;
  partnerId: string;
  amount: number;
  status: PayoutStatus;
  periodStart: number;
  periodEnd: number;
  events: string[];  // eventIds included in this payout
  createdAt: number;
  paidAt?: number;
}

export interface PartnerDashboard {
  partner: PartnerRecord;
  thisMonthRevenue: number;
  thisMonthEarnings: number;
  projectedPayout: number;
  recentEvents: RevenueEvent[];
  pendingPayouts: PayoutRecord[];
  acceleratorUnlocked: boolean;
  nextTierAt?: number;  // Revenue needed to unlock next tier
}


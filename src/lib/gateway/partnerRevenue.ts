// ─── Core Functions ─────────────────────────────────────────────────────────

function generateId(prefix: string): string {
  return `${prefix}_${Date.now()}_${Math.random().toString(36).substring(2, 8)}`;
}

/**
 * Calculate commission for a revenue event based on partner's tier config.
 */
export function calculateCommission(
  partner: PartnerRecord,
  grossRevenue: number,
  creditsConsumed: number = 0,
  currentMonthEarnings: number = 0
): number {
  const cfg = partner.commissionConfig;
  let commission = 0;

  if (cfg.type === 'percentage' || cfg.type === 'revenue_share') {
    commission = grossRevenue * cfg.rate;

    // Accelerator bonus check
    if (cfg.acceleratorThreshold && cfg.acceleratorBonus) {
      const monthlyRevenue = partner.cumulativeRevenue; // simplified
      if (monthlyRevenue > cfg.acceleratorThreshold) {
        commission += grossRevenue * cfg.acceleratorBonus;
      }
    }
  } else if (cfg.type === 'flat_per_call' && cfg.flatRatePerCredit) {
    commission = creditsConsumed * cfg.flatRatePerCredit;
  }

  // Monthly cap enforcement
  if (cfg.monthlyCap) {
    const headroom = cfg.monthlyCap - currentMonthEarnings;
    commission = Math.min(commission, Math.max(0, headroom));
  }

  return Math.round(commission * 100) / 100;
}

/**
 * Attribute an API key to a partner via referral code (called at key creation).
 */
export function attributeReferral(
  apiKey: string,
  referralCode: string
): { success: boolean; partnerId?: string; partnerName?: string } {
  const partnerId = referralIndex.get(referralCode.toUpperCase());
  if (!partnerId) {
    return { success: false };
  }
  apiKeyPartnerIndex.set(apiKey, partnerId);
  return { success: true, partnerId, partnerName: partnerRegistry.get(partnerId)?.name };
}

/**
 * Record a revenue event and credit the partner's commission ledger.
 */
export function recordRevenueEvent(
  apiKey: string,
  eventType: RevenueEventType,
  grossRevenue: number,
  creditsConsumed: number = 0
): RevenueEvent | null {
  const partnerId = apiKeyPartnerIndex.get(apiKey);
  if (!partnerId) return null;

  const partner = partnerRegistry.get(partnerId);
  if (!partner) return null;

  const commission = calculateCommission(partner, grossRevenue, creditsConsumed);

  const event: RevenueEvent = {
    eventId: generateId('evt'),
    partnerId,
    referredApiKey: apiKey,
    eventType,
    grossRevenue,
    creditsConsumed,
    commissionEarned: commission,
    timestamp: Date.now(),
  };

  revenueEvents.push(event);

  // Update partner ledger
  partner.cumulativeRevenue += grossRevenue;
  partner.cumulativeEarnings += commission;
  partner.pendingPayout += commission;

  // Auto tier upgrade check
  partner.tier = computeTier(partner.cumulativeRevenue);

  partnerRegistry.set(partnerId, partner);
  return event;
}

function computeTier(cumulativeRevenue: number): PartnerTier {
  if (cumulativeRevenue >= TIER_THRESHOLDS.gold) return 'gold';
  if (cumulativeRevenue >= TIER_THRESHOLDS.silver) return 'silver';
  return 'affiliate';
}

/**
 * Get a full partner dashboard with this month's stats, projections, and payout queue.
 */
export function getPartnerDashboard(partnerId: string): PartnerDashboard | null {
  const partner = partnerRegistry.get(partnerId);
  if (!partner) return null;

  const now = Date.now();
  const monthStart = new Date();
  monthStart.setDate(1);
  monthStart.setHours(0, 0, 0, 0);

  const thisMonthEvents = revenueEvents.filter(
    e => e.partnerId === partnerId && e.timestamp >= monthStart.getTime()
  );

  const thisMonthRevenue = thisMonthEvents.reduce((s, e) => s + e.grossRevenue, 0);
  const thisMonthEarnings = thisMonthEvents.reduce((s, e) => s + e.commissionEarned, 0);

  const cfg = partner.commissionConfig;
  const acceleratorUnlocked = !!(
    cfg.acceleratorThreshold && thisMonthRevenue >= cfg.acceleratorThreshold
  );

  const nextTierEntry = Object.entries(TIER_THRESHOLDS).find(
    ([tier, threshold]) =>
      TIER_THRESHOLDS[tier as PartnerTier] > partner.cumulativeRevenue && tier !== 'oem'
  );
  const nextTierAt = nextTierEntry
    ? nextTierEntry[1] - partner.cumulativeRevenue
    : undefined;

  const pendingPayouts = (payoutLedger.get(partnerId) || []).filter(
    p => p.status === 'pending' || p.status === 'approved'
  );

  return {
    partner,
    thisMonthRevenue,
    thisMonthEarnings,
    projectedPayout: partner.pendingPayout,
    recentEvents: revenueEvents.filter(e => e.partnerId === partnerId).slice(-10),
    pendingPayouts,
    acceleratorUnlocked,
    nextTierAt,
  };
}

/**
 * Process month-end payout batch for all partners.
 * In production, this triggers ACH/SWIFT or Stripe Connect payouts.
 */
export function processMonthEndPayouts(): PayoutRecord[] {
  const now = Date.now();
  const periodEnd = now;
  const periodStart = now - 30 * 24 * 60 * 60 * 1000;
  const processed: PayoutRecord[] = [];

  for (const [partnerId, partner] of partnerRegistry) {
    if (partner.pendingPayout < 100) continue; // Minimum payout threshold: $100

    const relevantEvents = revenueEvents
      .filter(e => e.partnerId === partnerId && e.timestamp >= periodStart && e.timestamp <= periodEnd)
      .map(e => e.eventId);

    const payout: PayoutRecord = {
      payoutId: generateId('pay'),
      partnerId,
      amount: partner.pendingPayout,
      status: 'approved',
      periodStart,
      periodEnd,
      events: relevantEvents,
      createdAt: now,
    };

    const existing = payoutLedger.get(partnerId) || [];
    existing.push(payout);
    payoutLedger.set(partnerId, existing);

    partner.pendingPayout = 0; // Clear balance after payout
    partnerRegistry.set(partnerId, partner);
    processed.push(payout);
  }

  return processed;
}

/**
 * Lookup a partner by referral code or partner ID.
 */
export function lookupPartner(query: string): PartnerRecord | null {
  // Try direct ID lookup
  if (partnerRegistry.has(query)) return partnerRegistry.get(query)!;
  // Try referral code
  const byCode = referralIndex.get(query.toUpperCase());
  if (byCode) return partnerRegistry.get(byCode) || null;
  return null;
}

export function getAllPartners(): PartnerRecord[] {
  return Array.from(partnerRegistry.values());
}
